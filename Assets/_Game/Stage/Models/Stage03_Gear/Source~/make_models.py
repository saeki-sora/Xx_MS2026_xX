"""
ステージ3「歯車ステージ」の仮の3Dモデル（OBJ）と床のタイルの絵（PNG）を作る（Claude 2026-10-29）。
外部のライブラリは使わない（Python 3 だけで動く）。作り直すとき:  python make_models.py
出力先はこのフォルダの1つ上（Assets/_Game/Stage/Models/Stage03_Gear/）。
座標はゲームの座標で書く: gx = 右, gy = 画面の上, h = 床からの高さ（カメラ側）。
OBJ は Y が上（Maya と同じ）なので、(gx, gy, h) → OBJ (-gx, h, gy) に直す。Unity の OBJ の取り込みが X を反転するので、
ステージ背景スタジオの「Mayaの向きを床に合わせる」（-90°回す）でちょうどゲームの座標に戻る。
面の向きは「外向きの向き」を渡して、その向きになるように頂点の順を自動で直す。
"""
import math
import os
import struct
import zlib

OUT = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))

MATERIALS = {
    # 名前: (色 RGB 0-1, 説明)
    "G3_Floor": ((0.70, 0.74, 0.92), "通り道の床タイル"),
    "G3_Gold": ((0.88, 0.64, 0.27), "歯車の金"),
    "G3_Brass": ((0.42, 0.29, 0.13), "暗い真鍮"),
    "G3_Steel": ((0.17, 0.18, 0.30), "壁の紺色の金属"),
    "G3_Panel": ((0.26, 0.20, 0.42), "壁の上の板（紫）"),
    "G3_GlowCyan": ((0.25, 0.90, 1.00), "光る線（水色）"),
    "G3_GlowPink": ((1.00, 0.35, 0.85), "光る線（桃色）"),
    "G3_Hazard": ((1.00, 0.48, 0.12), "動く壁の橙"),
}


def to_obj(p):
    gx, gy, h = p
    return (-gx, h, gy)


def sub(a, b):
    return (a[0] - b[0], a[1] - b[1], a[2] - b[2])


def cross(a, b):
    return (a[1] * b[2] - a[2] * b[1], a[2] * b[0] - a[0] * b[2], a[0] * b[1] - a[1] * b[0])


def dot(a, b):
    return a[0] * b[0] + a[1] * b[1] + a[2] * b[2]


class Mesh:
    def __init__(self):
        self.objects = []  # (name, [(material, [face])]) face = [(v, vt)]
        self.verts = []
        self.uvs = []

    def begin(self, name):
        self.current = (name, [])
        self.objects.append(self.current)

    def face(self, pts, normal, material, uvs=None):
        """pts: ゲームの座標の点（平らな多角形・凸）。normal: 外向き（ゲームの座標）。"""
        obj = [to_obj(p) for p in pts]
        n = to_obj(normal)
        if dot(cross(sub(obj[1], obj[0]), sub(obj[2], obj[0])), n) < 0:
            obj = obj[::-1]
            uvs = uvs[::-1] if uvs else None
        idx = []
        for i, v in enumerate(obj):
            self.verts.append(v)
            vi = len(self.verts)
            if uvs:
                self.uvs.append(uvs[i])
                ti = len(self.uvs)
            else:
                ti = None
            idx.append((vi, ti))
        groups = self.current[1]
        if not groups or groups[-1][0] != material:
            groups.append((material, []))
        groups[-1][1].append(idx)

    def write(self, path):
        lines = ["# Stage03_Gear (generated by make_models.py)", "mtllib stage03_gear.mtl"]
        lines += ["v %.4f %.4f %.4f" % v for v in self.verts]
        lines += ["vt %.4f %.4f" % t for t in self.uvs]
        for name, groups in self.objects:
            lines.append("g " + name)
            for material, faces in groups:
                lines.append("usemtl " + material)
                for f in faces:
                    lines.append("f " + " ".join(("%d/%d" % (v, t)) if t else str(v) for v, t in f))
        with open(path, "w", encoding="utf-8", newline="\n") as fp:
            fp.write("\n".join(lines) + "\n")


# ───────── 形 ─────────

def box(m, x0, x1, y0, y1, h0, h1, mat, top_mat=None, uv_scale=None, bottom=False):
    top_mat = top_mat or mat
    c = [(x0, y0), (x1, y0), (x1, y1), (x0, y1)]
    top = [(x, y, h1) for x, y in c]
    uvs = [(x * uv_scale, y * uv_scale) for x, y in c] if uv_scale else None
    m.face(top, (0, 0, 1), top_mat, uvs)
    if bottom:
        m.face([(x, y, h0) for x, y in c], (0, 0, -1), mat)
    m.face([(x0, y0, h0), (x1, y0, h0), (x1, y0, h1), (x0, y0, h1)], (0, -1, 0), mat)
    m.face([(x1, y0, h0), (x1, y1, h0), (x1, y1, h1), (x1, y0, h1)], (1, 0, 0), mat)
    m.face([(x1, y1, h0), (x0, y1, h0), (x0, y1, h1), (x1, y1, h1)], (0, 1, 0), mat)
    m.face([(x0, y1, h0), (x0, y0, h0), (x0, y0, h1), (x0, y1, h1)], (-1, 0, 0), mat)


def prism(m, outline, cx, cy, h0, h1, side_mat, top_mat, bottom=False):
    """星形（真ん中から全部見える）の輪郭を立ち上げる。上は真ん中からの扇。"""
    n = len(outline)
    for i in range(n):
        a = outline[i]
        b = outline[(i + 1) % n]
        m.face([(cx, cy, h1), (a[0], a[1], h1), (b[0], b[1], h1)], (0, 0, 1), top_mat)
        if bottom:
            m.face([(cx, cy, h0), (a[0], a[1], h0), (b[0], b[1], h0)], (0, 0, -1), side_mat)
        mx, my = (a[0] + b[0]) / 2 - cx, (a[1] + b[1]) / 2 - cy
        ex, ey = b[0] - a[0], b[1] - a[1]
        nx, ny = ey, -ex
        if nx * mx + ny * my < 0:
            nx, ny = -nx, -ny
        m.face([(a[0], a[1], h0), (b[0], b[1], h0), (b[0], b[1], h1), (a[0], a[1], h1)], (nx, ny, 0), side_mat)


def circle(cx, cy, r, n=48):
    return [(cx + r * math.cos(2 * math.pi * i / n), cy + r * math.sin(2 * math.pi * i / n)) for i in range(n)]


def cylinder(m, cx, cy, r, h0, h1, side_mat, top_mat=None, n=48):
    prism(m, circle(cx, cy, r, n), cx, cy, h0, h1, side_mat, top_mat or side_mat)


def ring(m, cx, cy, r0, r1, h0, h1, mat, n=64):
    """平らな輪（上の面と外・内の側面）。"""
    for i in range(n):
        a0 = 2 * math.pi * i / n
        a1 = 2 * math.pi * (i + 1) / n
        p = lambda r, a, h: (cx + r * math.cos(a), cy + r * math.sin(a), h)
        m.face([p(r0, a0, h1), p(r1, a0, h1), p(r1, a1, h1), p(r0, a1, h1)], (0, 0, 1), mat)
        mid = (a0 + a1) / 2
        m.face([p(r1, a0, h0), p(r1, a1, h0), p(r1, a1, h1), p(r1, a0, h1)], (math.cos(mid), math.sin(mid), 0), mat)
        m.face([p(r0, a1, h0), p(r0, a0, h0), p(r0, a0, h1), p(r0, a1, h1)], (-math.cos(mid), -math.sin(mid), 0), mat)


def gear_outline(cx, cy, radius, depth, teeth):
    pts = []
    root = radius - depth
    for i in range(teeth):
        a = 2 * math.pi * i / teeth
        p = 2 * math.pi / teeth
        for frac, r in ((0.0, root), (0.14, radius), (0.42, radius), (0.56, root)):
            ang = a + frac * p
            pts.append((cx + r * math.cos(ang), cy + r * math.sin(ang)))
    return pts


def gear(m, radius, teeth, depth, height, hub_r, glow_r=None, base=0.0):
    prism(m, gear_outline(0, 0, radius, depth, teeth), 0, 0, base, base + height, "G3_Gold", "G3_Gold", bottom=True)
    # 内側の一段低い板（暗い真鍮）と、軸
    ring(m, 0, 0, hub_r * 1.6, radius - depth - 0.25, base + height, base + height + 0.03, "G3_Brass")
    cylinder(m, 0, 0, hub_r, base, base + height + 0.16, "G3_Steel", "G3_Steel", n=32)
    if glow_r:
        ring(m, 0, 0, glow_r - 0.07, glow_r + 0.07, base + height + 0.03, base + height + 0.05, "G3_GlowCyan")


def walled_block(m, x0, x1, y0, y1, height, trim="G3_GlowCyan", plate="G3_Panel", body="G3_Steel"):
    box(m, x0, x1, y0, y1, 0.0, height, body)
    inset = 0.1
    box(m, x0 + inset, x1 - inset, y0 + inset, y1 - inset, height, height + 0.06, plate)
    w = 0.12
    e = 0.04
    box(m, x0 + e, x1 - e, y0 + e, y0 + e + w, height, height + 0.1, trim)
    box(m, x0 + e, x1 - e, y1 - e - w, y1 - e, height, height + 0.1, trim)
    box(m, x0 + e, x0 + e + w, y0 + e + w, y1 - e - w, height, height + 0.1, trim)
    box(m, x1 - e - w, x1 - e, y0 + e + w, y1 - e - w, height, height + 0.1, trim)


